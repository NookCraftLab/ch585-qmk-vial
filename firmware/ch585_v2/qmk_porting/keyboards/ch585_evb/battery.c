/*
 * battery.c — 电池管理实现（评估板用模拟值，接口预留）
 *
 * 评估板没有电池硬件，所有函数返回模拟值。
 * 后续最终键盘 PCB 有电池硬件后，修改本文件内部实现即可。
 *
 * 硬件接入指引（后续实现参考）：
 * - 电池电压检测：电池正极 → 分压电阻（100K+100K）→ ADC 引脚
 *   ADC 读取电压 ×2 = 电池电压（分压比 1:2）
 * - 充电状态检测：充电芯片（如 TP4056）的 CHRG/STDBY 引脚 → GPIO
 *   CHRG 低电平=充电中，STDBY 低电平=充电完成
 * - USB 检测：USB VBUS → 分压电阻 → GPIO（或直接用 usb_is_connected()）
 */

